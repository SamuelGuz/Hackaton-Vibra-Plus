-- Huellitas: esquema de la base de datos.
-- Sale de la hoja "Huellitas_DB_Estructura": una tabla por pestaña, mismas columnas y en el mismo orden.
-- Los ids son números consecutivos para que se lean fácil en Google Sheets.
-- Solo se restringen con CHECK los valores que ya están definidos en los planes (roles, especie,
-- estado del animal, estado de confirmación, semáforo, tipo de movimiento). El resto es texto libre.

BEGIN;

-- Personas del equipo que usan el bot y el panel
CREATE TABLE usuarios (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  telefono           text NOT NULL UNIQUE,
  telegram_id        text,
  nombre             text NOT NULL,
  rol                text NOT NULL CHECK (rol IN ('admin','cuidador','bienestar','adopciones','comunicacion','voluntario')),
  activo             boolean NOT NULL DEFAULT true,
  recibe_alertas     boolean NOT NULL DEFAULT false,
  orden_escalamiento smallint,
  creado_en          timestamptz NOT NULL DEFAULT now()
);

-- Reglas y umbrales que edita la administradora (consumo, horas de cierre, etc.)
CREATE TABLE config (
  clave       text PRIMARY KEY,
  valor       text NOT NULL,
  descripcion text
);

-- Gente de afuera: donantes, padrinos, voluntarios, hogares temporales, adoptantes
CREATE TABLE personas (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre               text NOT NULL,
  telefono             text UNIQUE,
  email                text,
  zona                 text,
  es_donante           boolean NOT NULL DEFAULT false,
  es_padrino           boolean NOT NULL DEFAULT false,
  es_voluntario        boolean NOT NULL DEFAULT false,
  es_hogar_temporal    boolean NOT NULL DEFAULT false,
  es_adoptante         boolean NOT NULL DEFAULT false,
  habilidades          text,
  tiene_vehiculo       boolean NOT NULL DEFAULT false,
  consentimiento_datos boolean NOT NULL DEFAULT false,
  fecha_consentimiento timestamptz,
  creado_en            timestamptz NOT NULL DEFAULT now()
);

-- Lo que llega por audio, foto o texto y lo que la IA entendió
CREATE TABLE registros_ia (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id    bigint REFERENCES usuarios(id),
  persona_id    bigint REFERENCES personas(id),
  canal         text NOT NULL DEFAULT 'whatsapp',   -- whatsapp, panel
  tipo_entrada  text NOT NULL,                      -- texto, audio, imagen, boton
  media_url     text,
  transcripcion text,
  acciones_json jsonb,
  confianza     numeric(3,2) CHECK (confianza BETWEEN 0 AND 1),
  estado        text NOT NULL DEFAULT 'por_confirmar' CHECK (estado IN ('por_confirmar','confirmado','corregido','anulado')),
  expira_en     timestamptz,
  creado_en     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE animales (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre           text NOT NULL,
  alias            text[] NOT NULL DEFAULT '{}',
  especie          text NOT NULL CHECK (especie IN ('perro','gato')),
  sexo             text CHECK (sexo IN ('macho','hembra')),
  edad_aprox_meses integer CHECK (edad_aprox_meses >= 0),
  tamano           text,                 -- pequeno, mediano, grande
  color            text,
  energia          text,                 -- baja, media, alta
  caracter         text,
  convive_perros   boolean,              -- vacío = no se sabe
  convive_gatos    boolean,
  convive_ninos    boolean,
  canil            text,
  estado           text NOT NULL DEFAULT 'cuarentena'
                   CHECK (estado IN ('cuarentena','tratamiento','adoptable','hogar_temporal','adoptado','fallecido','devuelto')),
  esterilizado     boolean NOT NULL DEFAULT false,
  fecha_ingreso    date NOT NULL DEFAULT current_date,
  lugar_rescate    text,
  motivo_ingreso   text,
  advertencias     text[] NOT NULL DEFAULT '{}',   -- lo que NO puede pasar (caso Bruno)
  foto_url         text,
  creado_en        timestamptz NOT NULL DEFAULT now(),
  creado_por       bigint REFERENCES usuarios(id),
  registro_id      bigint REFERENCES registros_ia(id)
);

CREATE TABLE historial_estados (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  animal_id       bigint NOT NULL REFERENCES animales(id),
  estado_anterior text,
  estado_nuevo    text NOT NULL,
  motivo          text,
  fecha           timestamptz NOT NULL DEFAULT now(),
  creado_por      bigint REFERENCES usuarios(id)
);

CREATE TABLE tratamientos (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  animal_id        bigint NOT NULL REFERENCES animales(id),
  medicamento      text NOT NULL,
  dosis            numeric NOT NULL CHECK (dosis > 0),
  unidad           text NOT NULL,        -- ml, pastilla, mg
  frecuencia_horas integer NOT NULL CHECK (frecuencia_horas > 0),
  hora_inicio      time NOT NULL,
  fecha_inicio     date NOT NULL,
  fecha_fin        date CHECK (fecha_fin >= fecha_inicio),
  indicado_por     text,                 -- veterinario que lo formuló
  activo           boolean NOT NULL DEFAULT true,
  creado_en        timestamptz NOT NULL DEFAULT now(),
  creado_por       bigint REFERENCES usuarios(id)
);

-- Dosis dadas, observaciones, avances, vacunas, peso...
CREATE TABLE eventos_salud (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  animal_id      bigint NOT NULL REFERENCES animales(id),
  tratamiento_id bigint REFERENCES tratamientos(id),
  tipo           text NOT NULL,          -- dosis, observacion, avance, vacuna, peso
  detalle        text,
  valor          text,
  fecha_hora     timestamptz NOT NULL DEFAULT now(),
  estado         text NOT NULL DEFAULT 'por_confirmar' CHECK (estado IN ('por_confirmar','confirmado','corregido','anulado')),
  creado_por     bigint REFERENCES usuarios(id),
  registro_id    bigint REFERENCES registros_ia(id)
);

CREATE TABLE estancias_hogar_temporal (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  animal_id  bigint NOT NULL REFERENCES animales(id),
  persona_id bigint NOT NULL REFERENCES personas(id),
  desde      date NOT NULL,
  hasta      date CHECK (hasta >= desde),
  notas      text
);

CREATE TABLE solicitudes_adopcion (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  persona_id            bigint NOT NULL REFERENCES personas(id),
  animal_id             bigint REFERENCES animales(id),   -- vacío si no pidió uno en particular
  respuestas_json       jsonb,                            -- el formulario completo
  tipo_vivienda         text,
  vivienda_propia       boolean,
  cerramientos          boolean,                          -- mallas, rejas
  acuerdo_familiar      boolean,
  presupuesto_mensual   integer CHECK (presupuesto_mensual >= 0),
  experiencia           text,
  acepta_seguimientos   boolean,
  acepta_esterilizacion boolean,
  color                 text CHECK (color IN ('verde','amarillo','rojo')),  -- montón sugerido
  motivos               text,                             -- por qué quedó en ese montón
  estado                text NOT NULL DEFAULT 'nueva',    -- nueva, en_revision, aprobada, rechazada
  revisada_por          bigint REFERENCES usuarios(id),
  creado_en             timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE adopciones (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_id      bigint REFERENCES solicitudes_adopcion(id),
  animal_id         bigint NOT NULL REFERENCES animales(id),
  persona_id        bigint NOT NULL REFERENCES personas(id),
  fecha_entrega     date NOT NULL,
  pasaporte_url     text,
  estado            text NOT NULL DEFAULT 'activa',      -- activa, devuelta
  fecha_devolucion  date CHECK (fecha_devolucion >= fecha_entrega),
  motivo_devolucion text,
  creado_por        bigint REFERENCES usuarios(id)
);

-- Seguimientos después de la adopción (días 2, 5, 15, 30, 90)
CREATE TABLE checkins (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  adopcion_id     bigint NOT NULL REFERENCES adopciones(id),
  dia             smallint NOT NULL CHECK (dia > 0),
  programado_para date NOT NULL,
  enviado_en      timestamptz,
  respuesta       text,
  texto           text,
  riesgo          text CHECK (riesgo IN ('verde','amarillo','rojo')),
  atendido_por    bigint REFERENCES usuarios(id),
  atendido_en     timestamptz,
  UNIQUE (adopcion_id, dia)
);

CREATE TABLE padrinazgos (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  persona_id    bigint NOT NULL REFERENCES personas(id),
  animal_id     bigint NOT NULL REFERENCES animales(id),
  monto_mensual integer CHECK (monto_mensual >= 0),
  desde         date NOT NULL,
  hasta         date CHECK (hasta >= desde),
  activo        boolean NOT NULL DEFAULT true
);

-- Comida, medicamentos e insumos, con su consumo para calcular los días que alcanzan
CREATE TABLE catalogo_items (
  id                           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre                       text NOT NULL UNIQUE,
  tipo                         text NOT NULL,     -- comida, medicamento, limpieza
  unidad                       text NOT NULL,     -- bulto, caja, frasco
  kg_por_unidad                numeric CHECK (kg_por_unidad > 0),
  especie_objetivo             text CHECK (especie_objetivo IN ('perro','gato')),
  consumo_diario_kg_por_animal numeric CHECK (consumo_diario_kg_por_animal >= 0),
  precio_ref                   integer CHECK (precio_ref >= 0),
  umbral_dias                  integer CHECK (umbral_dias >= 0)
);

CREATE TABLE necesidades (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo            text NOT NULL,
  descripcion       text,
  tipo              text,               -- comida, veterinaria, insumo, plata
  item_id           bigint REFERENCES catalogo_items(id),
  animal_id         bigint REFERENCES animales(id),
  cantidad_meta     numeric CHECK (cantidad_meta >= 0),
  cantidad_cubierta numeric NOT NULL DEFAULT 0 CHECK (cantidad_cubierta >= 0),
  monto_meta        integer CHECK (monto_meta >= 0),
  monto_cubierto    integer NOT NULL DEFAULT 0 CHECK (monto_cubierto >= 0),
  prioridad         text,               -- alta, media, baja
  estado            text NOT NULL DEFAULT 'abierta',  -- abierta, cubierta, cerrada
  fecha_limite      date,
  creado_en         timestamptz NOT NULL DEFAULT now(),
  creado_por        bigint REFERENCES usuarios(id)
);

-- Entradas (+) y salidas (−) de bodega. "Se abrió un bulto" es cantidad -1.
CREATE TABLE inventario_movimientos (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id      bigint NOT NULL REFERENCES catalogo_items(id),
  cantidad     numeric NOT NULL CHECK (cantidad <> 0),
  origen       text,                    -- panel, bot, donacion, compra
  persona_id   bigint REFERENCES personas(id),
  necesidad_id bigint REFERENCES necesidades(id),
  fecha_hora   timestamptz NOT NULL DEFAULT now(),
  creado_por   bigint REFERENCES usuarios(id),
  registro_id  bigint REFERENCES registros_ia(id)
);

-- Clínicas, bancos y proveedores (las clínicas fían hasta limite_credito)
CREATE TABLE entidades (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre         text NOT NULL,
  tipo           text NOT NULL CHECK (tipo IN ('clinica','banco','proveedor')),
  limite_credito integer CHECK (limite_credito >= 0),
  telefono       text,
  notas          text
);

-- ingreso y gasto mueven la caja. factura = compra a crédito (sube la deuda con la entidad).
-- abono = pago de esa deuda (sale de caja y baja la deuda).
CREATE TABLE movimientos_financieros (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo         text NOT NULL CHECK (tipo IN ('ingreso','gasto','factura','abono')),
  monto        integer NOT NULL CHECK (monto > 0),   -- pesos, sin decimales
  categoria    text,                                 -- comida, veterinaria, donacion, padrino, rifa...
  entidad_id   bigint REFERENCES entidades(id),
  persona_id   bigint REFERENCES personas(id),
  animal_id    bigint REFERENCES animales(id),
  necesidad_id bigint REFERENCES necesidades(id),
  concepto     text,
  fecha        date NOT NULL DEFAULT current_date,
  medio        text,                                 -- efectivo, nequi, transferencia
  soporte_url  text,                                 -- foto de la factura o el comprobante
  estado       text NOT NULL DEFAULT 'por_confirmar' CHECK (estado IN ('por_confirmar','confirmado','corregido','anulado')),
  creado_en    timestamptz NOT NULL DEFAULT now(),
  creado_por   bigint REFERENCES usuarios(id),
  registro_id  bigint REFERENCES registros_ia(id),
  CHECK (tipo NOT IN ('factura','abono') OR entidad_id IS NOT NULL)
);

-- Alguien dice "yo pongo eso" y se le guarda un rato
CREATE TABLE apartados (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  necesidad_id bigint NOT NULL REFERENCES necesidades(id),
  persona_id   bigint NOT NULL REFERENCES personas(id),
  cantidad     numeric CHECK (cantidad > 0),
  monto        integer CHECK (monto > 0),
  vence_en     timestamptz,
  estado       text NOT NULL DEFAULT 'activo',       -- activo, cumplido, vencido
  creado_en    timestamptz NOT NULL DEFAULT now()
);

-- Historias para padrinos y redes, armadas con hechos de la bitácora
CREATE TABLE historias (
  id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  animal_id               bigint NOT NULL REFERENCES animales(id),
  tipo                    text,                      -- padrino, redes
  periodo                 text,                      -- p. ej. 2026-10
  texto                   text,
  hechos_json             jsonb,
  destinatario_persona_id bigint REFERENCES personas(id),
  estado                  text NOT NULL DEFAULT 'borrador',  -- borrador, aprobada, enviada
  aprobada_por            bigint REFERENCES usuarios(id),
  enviada_en              timestamptz,
  creado_en               timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE turnos (
  id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha  date NOT NULL,
  franja text NOT NULL,                  -- manana, tarde
  cupo   integer NOT NULL CHECK (cupo > 0),
  UNIQUE (fecha, franja)
);

CREATE TABLE inscripciones_turno (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  turno_id      bigint NOT NULL REFERENCES turnos(id),
  persona_id    bigint NOT NULL REFERENCES personas(id),
  estado        text NOT NULL DEFAULT 'inscrito',     -- inscrito, confirmado, asistio, falto
  recordado_en  timestamptz,
  confirmado_en timestamptz,
  UNIQUE (turno_id, persona_id)
);

CREATE TABLE microtareas (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo       text NOT NULL,
  tipo         text,
  animal_id    bigint REFERENCES animales(id),
  fecha_limite date,
  persona_id   bigint REFERENCES personas(id),
  estado       text NOT NULL DEFAULT 'abierta'        -- abierta, tomada, hecha
);

CREATE TABLE alertas (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo               text NOT NULL,      -- comida, dosis, deuda, checkin
  referencia_tabla   text,
  referencia_id      bigint,
  mensaje            text NOT NULL,
  destinatario_id    bigint REFERENCES usuarios(id),
  nivel_escalamiento smallint NOT NULL DEFAULT 0,
  estado             text NOT NULL DEFAULT 'pendiente',  -- pendiente, enviada, atendida
  enviada_en         timestamptz,
  atendida_por       bigint REFERENCES usuarios(id),
  atendida_en        timestamptz
);

-- Índices para las consultas de todos los días (ficha del animal, dosis de hoy, plata de la semana)
CREATE INDEX ON historial_estados (animal_id);
CREATE INDEX ON tratamientos (animal_id) WHERE activo;
CREATE INDEX ON eventos_salud (animal_id, fecha_hora);
CREATE INDEX ON eventos_salud (tratamiento_id, fecha_hora);
CREATE INDEX ON inventario_movimientos (item_id, fecha_hora);
CREATE INDEX ON movimientos_financieros (fecha);
CREATE INDEX ON movimientos_financieros (entidad_id);
CREATE INDEX ON solicitudes_adopcion (estado, color);
CREATE INDEX ON checkins (programado_para) WHERE atendido_en IS NULL;
CREATE INDEX ON alertas (estado);

COMMIT;
