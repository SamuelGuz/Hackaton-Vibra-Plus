/** Clave de búsqueda de un nombre: minúsculas, sin tildes y sin espacios sobrantes. */
export function claveDe(nombre: string): string {
  return nombre
    .trim()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
}

